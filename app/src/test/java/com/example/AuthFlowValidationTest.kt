package com.example

import com.example.util.UsernameUtils
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class AuthFlowValidationTest {

    @Test
    fun testValidEmailAddressesAccepted() {
        assertTrue(UsernameUtils.isEmailAddress("user@example.com"))
        assertTrue(UsernameUtils.isEmailAddress("ronaldomazive915@gmail.com"))
        assertTrue(UsernameUtils.isEmailAddress("test.name+filter@domain.co.mz"))
        assertTrue(UsernameUtils.isEmailAddress("admin@ronycine.app"))
    }

    @Test
    fun testInvalidEmailAddressesRejected() {
        assertFalse(UsernameUtils.isEmailAddress("@username"))
        assertFalse(UsernameUtils.isEmailAddress("username"))
        assertFalse(UsernameUtils.isEmailAddress("notanemail"))
        assertFalse(UsernameUtils.isEmailAddress(""))
        assertFalse(UsernameUtils.isEmailAddress("   "))
    }

    @Test
    fun testAutoGeneratedUsernameCreation() {
        val autoUsername = UsernameUtils.generateAutoUsername("João Silva", "joao.silva@gmail.com")
        assertTrue("Auto username should not be blank", autoUsername.isNotBlank())
        assertTrue("Auto username should contain alphanumeric or underscore", autoUsername.matches(Regex("^[a-z0-9_]+$")))
        assertTrue("Auto username should be derived from email or name", autoUsername.startsWith("joao") || autoUsername.startsWith("user"))
    }

    @Test
    fun testAutoGeneratedUsernameWithEmptyName() {
        val autoUsername = UsernameUtils.generateAutoUsername("", "pedro@test.com")
        assertTrue(autoUsername.isNotBlank())
        assertTrue(autoUsername.startsWith("pedro"))
    }

    @Test
    fun testAutoGeneratedUsernameWithSpecialCharacters() {
        val autoUsername = UsernameUtils.generateAutoUsername("Ana & Maria! #1", "ana.maria99@domain.com")
        assertTrue(autoUsername.isNotBlank())
        assertTrue(autoUsername.matches(Regex("^[a-z0-9_]+$")))
    }

    @Test
    fun testLegacyUsernameNormalizationPreserved() {
        assertEquals("ronaldo", UsernameUtils.normalize("@ronaldo"))
        assertEquals("ronaldo_12", UsernameUtils.normalize("  @RONALDO_12  "))
        assertEquals("admin", UsernameUtils.normalize("admin"))
    }
}
